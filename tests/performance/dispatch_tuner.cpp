  volatile SizeT sink = 0;

  struct ThresholdSuggestions
  {
    SizeT classicMultTotal = BIGMATH_CLASSIC_MULTIPLICATION_THRESHOLD;
    SizeT classicMinLimb = BIGMATH_CLASSIC_MIN_LIMB_THRESHOLD;
    SizeT toom3Total = BIGMATH_TOOM3_MULTIPLICATION_THRESHOLD;
    SizeT nttMultTotal = BIGMATH_NTT_MULTIPLICATION_THRESHOLD;
    SizeT nttSquare = BIGMATH_NTT_SQUARE_THRESHOLD;
    SizeT bzDivisor = BIGMATH_BZ_DIVISOR_THRESHOLD;
    SizeT newtonMedium = BIGMATH_NEWTON_MEDIUM_B;
    SizeT newtonSkewNumerator = BIGMATH_NEWTON_SKEW_NUMERATOR;
    SizeT newtonSkewDenominator = BIGMATH_NEWTON_SKEW_DENOMINATOR;
    SizeT coldSquare = BIGMATH_NTT_SQUARE_COLD_THRESHOLD;
    SizeT coldArea = BIGMATH_NTT_COLD_AREA_THRESHOLD;
    SizeT divBz = BIGMATH_DIV_BZ_MIN_B;
    SizeT divNewton = BIGMATH_DIV_NEWTON_MIN_B;
    SizeT divSkew = BIGMATH_DIV_NEWTON_SKEW_MIN_B;
    SizeT divNear2 = BIGMATH_DIV_NEWTON_NEAR2_MIN_B;
    SizeT divQuotient = BIGMATH_DIV_QSIZED_MIN_QUOTIENT;
  };

  vector<DataT> RandomNumber(SizeT limbs, mt19937_64 &gen)
  {
    vector<DataT> value(limbs);
    for (auto &limb : value)
      limb = gen() & LimbMask;
    value.back() |= DataT{1} << (LimbBits - 1);
    return value;
  }

  template <typename Fn>
  double BestMs(Fn &&fn, int reps)
  {
    double best = numeric_limits<double>::max();
    for (int i = 0; i < reps; ++i)
    {
      auto start = chrono::steady_clock::now();
      SizeT checksum = fn();
      auto end = chrono::steady_clock::now();
      sink += checksum;
      best = min(best, chrono::duration<double, milli>(end - start).count());
    }
    return best;
  }

  int RepsForLimbs(SizeT limbs)
  {
    if (limbs <= 128)
      return 7;
    if (limbs <= 4096)
      return 5;
    return 3;
  }

  string Winner(initializer_list<pair<string, double>> values)
  {
    auto best = values.begin();
    for (auto it = values.begin(); it != values.end(); ++it)
      if (it->second < best->second)
        best = it;
    return best->first;
  }

