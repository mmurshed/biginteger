  void WriteThresholdHeader(string const &path, ThresholdSuggestions const &s)
  {
    ofstream out(path);
    if (!out)
      throw runtime_error("failed to open dispatch threshold header: " + path);

    out << "#pragma once\n// Generated by dispatch_tuner on the target hardware.\n";
    out << "#if BIGMATH_LIMB_64 == " << BIGMATH_LIMB_64 << '\n';
    auto emit = [&](const char *name, SizeT value) {
      out << "#ifndef " << name << "\n#define " << name << ' ' << value << "\n#endif\n";
    };
    emit("BIGMATH_CLASSIC_MULTIPLICATION_THRESHOLD", s.classicMultTotal);
    emit("BIGMATH_CLASSIC_MIN_LIMB_THRESHOLD", s.classicMinLimb);
    emit("BIGMATH_TOOM3_MULTIPLICATION_THRESHOLD", s.toom3Total);
    emit("BIGMATH_NTT_MULTIPLICATION_THRESHOLD", s.nttMultTotal);
    emit("BIGMATH_NTT_SQUARE_THRESHOLD", s.nttSquare);
#if BIGMATH_LIMB_64
    emit("BIGMATH_NTT_SQUARE_COLD_THRESHOLD", s.coldSquare);
    emit("BIGMATH_NTT_COLD_AREA_THRESHOLD", s.coldArea);
    emit("BIGMATH_DIV_BZ_MIN_B", s.divBz);
    emit("BIGMATH_DIV_NEWTON_MIN_B", s.divNewton);
    emit("BIGMATH_DIV_NEWTON_SKEW_MIN_B", s.divSkew);
    emit("BIGMATH_DIV_NEWTON_SKEW_RATIO", BIGMATH_DIV_NEWTON_SKEW_RATIO);
    emit("BIGMATH_DIV_NEWTON_NEAR2_MIN_B", s.divNear2);
    emit("BIGMATH_DIV_QSIZED_MIN_QUOTIENT", s.divQuotient);
#else
    emit("BIGMATH_BZ_DIVISOR_THRESHOLD", s.bzDivisor);
    emit("BIGMATH_NEWTON_MEDIUM_B", s.newtonMedium);
    emit("BIGMATH_NEWTON_SKEW_NUMERATOR", s.newtonSkewNumerator);
    emit("BIGMATH_NEWTON_SKEW_DENOMINATOR", s.newtonSkewDenominator);
#endif
    out << "#endif\n";
    if (!out) throw runtime_error("failed to write " + path);
  }

  // Require a 5% lead at two adjacent sizes before reporting a crossover.
  struct Crossover
  {
    SizeT previous = 0, first = 0;
    void Observe(SizeT size, double incumbent, double challenger)
    {
      if (challenger * 1.05 >= incumbent) previous = 0;
      else if (!previous) previous = size;
      else if (!first) first = previous;
    }
  };

  template <class Fn>
  double ParkedMs(Fn fn)
  {
    double best = numeric_limits<double>::max();
    for (int i = 0; i < 3; ++i)
    {
      do { this_thread::sleep_for(chrono::milliseconds(2)); } while (ParallelWarm());
      best = min(best, BestMs(fn, 1));
    }
    return best;
  }

  template <class Fn>
  void TimeDispatch(const char *operation, const char *state, SizeT a, SizeT b, Fn fn)
  {
    vector<double> elapsed;
    for (int sample = 0; sample < 9; ++sample)
    {
      if (string_view(state) == "parked")
        do { this_thread::sleep_for(chrono::milliseconds(2)); } while (ParallelWarm());
      const auto start = chrono::steady_clock::now();
      const SizeT checksum = fn();
      const auto end = chrono::steady_clock::now();
      sink += checksum;
      elapsed.push_back(chrono::duration<double, micro>(end - start).count());
    }
    sort(elapsed.begin(), elapsed.end());
    cout << operation << ',' << state << ',' << a << ',' << b << ','
         << fixed << setprecision(6) << elapsed[elapsed.size() / 2] << '\n';
  }

  void Holdout()
  {
    mt19937_64 gen(0xE86452A2);
    const auto base = BigInteger::Base();
    cout << "operation,state,a_limbs,b_limbs,median_us\n";
    for (const auto [aSize, bSize] : vector<pair<SizeT, SizeT>>{
             {27, 27}, {29, 29}, {35, 35}, {55, 55}, {312, 312}, {336, 336},
             {421, 421}, {496, 496}, {531, 531}, {700, 700}, {991, 991}, {1131, 1131},
             {1501, 1501}, {1981, 1981}, {2129, 2129}, {2461, 2461},
             {2639, 2639}, {2949, 2949}, {3973, 3973}, {4219, 4219}, {6173, 6173},
             {703, 23}, {859, 29}, {1631, 37}, {2101, 73}, {1337, 119},
             {3007, 359}, {4817, 1221}})
    {
      const auto a = RandomNumber(aSize, gen), b = RandomNumber(bSize, gen);
      if (Multiply(a, b, base) != ClassicMultiplication::Multiply(a, b, base))
        throw runtime_error("holdout multiplication mismatch");
      auto run = [&] { return Multiply(a, b, base).size(); };
      const char *op = aSize == bSize ? "mul-balanced" : "mul-skew";
      TimeDispatch(op, "burst", aSize, bSize, run);
      TimeDispatch(op, "parked", aSize, bSize, run);
    }

    for (const SizeT size : {303, 340, 378, 484, 535, 599, 627, 723, 811, 991, 1153,
                            1277, 1349, 1441, 1973, 2123, 2483, 2671, 3011, 4001, 4229, 6037})
    {
      const auto a = RandomNumber(size, gen);
      if (Square(a, base) != ClassicMultiplication::Multiply(a, a, base))
        throw runtime_error("holdout square mismatch");
      auto run = [&] { return Square(a, base).size(); };
      TimeDispatch("square", "burst", size, size, run);
      TimeDispatch("square", "parked", size, size, run);
    }

    struct DivisionShape
    {
      const char *operation;
      SizeT a, b;
    };
    for (const auto [op, aSize, bSize] : vector<DivisionShape>{
             {"div-bz", 146, 73}, {"div-bz", 174, 87}, {"div-bz", 202, 101},
             {"div-bz", 262, 131}, {"div-bz", 378, 189},
             {"div-balanced", 2042, 1021}, {"div-balanced", 2894, 1447},
             {"div-balanced", 3154, 1577}, {"div-balanced", 3622, 1811},
             {"div-balanced", 4502, 2251}, {"div-balanced", 6298, 3149},
             {"div-skew", 1653, 551}, {"div-skew", 2217, 739}, {"div-skew", 2397, 799},
             {"div-skew", 2865, 955}, {"div-skew", 3459, 1153},
             {"div-near2", 4489, 2565}, {"div-near2", 5249, 2999},
             {"div-near2", 5557, 3175}, {"div-near2", 6533, 3733},
             {"div-short", 8028, 6021}, {"div-short", 11996, 8997},
             {"div-short", 12812, 9609}, {"div-short", 14212, 10659}})
    {
      const auto a = RandomNumber(aSize, gen), b = RandomNumber(bSize, gen);
      if (DivideAndRemainder(a, b, base) != FastDivision::DivideAndRemainder(a, b, base))
        throw runtime_error("holdout division mismatch");
      TimeDispatch(op, "burst", aSize, bSize, [&] {
        const auto [q, r] = DivideAndRemainder(a, b, base);
        return q.size() + r.size();
      });
    }
  }

  void TuneMultiplication(bool full, ThresholdSuggestions &s)
  {
    PrintHeader("Multiplication Dispatch");
    cout << "limbs_each,total_limbs,classic_ms,karatsuba_ms,toom3_ms,toom5_ms,ntt_burst_ms,ntt_parked_ms,winner\n";

    vector<SizeT> sizes = {
        8, 16, 24, 28, 32, 40, 48, 64, 96, 128, 192, 256, 288, 320, 352, 384, 448, 512, 576, 608, 640,
        1024, 2048, 4096, 8192, 12000, 16000};
    if (full)
    {
      sizes.push_back(20000);
      sizes.push_back(24576);
      sizes.push_back(32768);
    }

    mt19937_64 gen(0xB16B00B5);
    SizeT suggestedClassicTotal = CLASSIC_MULTIPLICATION_THRESHOLD;
    Crossover warmNtt, coldNtt;
    SizeT previousTotal = 0;
    bool foundClassicCrossover = false;
    SizeT suggestedMinLimb = 0;
    bool classicWinsPrefix = true;

    for (SizeT limbs : sizes)
    {
      vector<DataT> a = RandomNumber(limbs, gen);
      vector<DataT> b = RandomNumber(limbs, gen);
      int reps = RepsForLimbs(limbs);

      double classicMs = numeric_limits<double>::quiet_NaN();
      if (limbs <= 256)
      {
        classicMs = BestMs([&]() {
          auto r = ClassicMultiplication::Multiply(a, b, BigInteger::Base());
          return (SizeT)r.size();
        }, reps);
      }

      double karaMs = BestMs([&]() {
        auto r = KaratsubaMultiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);

      double toom3Ms = BestMs([&]() {
        auto r = ToomCookMultiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);

      double toom5Ms = BestMs([&]() {
        auto r = Toom5Multiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);

      auto transform = [&]() { return NTTMultiplication::Multiply(a, b, BigInteger::Base()).size(); };
      transform();
      double nttMs = BestMs(transform, reps);
      double parked = numeric_limits<double>::quiet_NaN();
      if (limbs >= 128 && limbs <= 2048)
      {
        parked = ParkedMs(transform);
        coldNtt.Observe(limbs, karaMs, parked);
      }
      string winner = limbs <= 256
                          ? Winner({{"classic", classicMs}, {"karatsuba", karaMs}, {"toom3", toom3Ms}, {"toom5", toom5Ms}, {"ntt", nttMs}})
                          : Winner({{"karatsuba", karaMs}, {"toom3", toom3Ms}, {"toom5", toom5Ms}, {"ntt", nttMs}});

      if (!foundClassicCrossover && previousTotal && limbs <= 256 && karaMs * 1.05 < classicMs)
      {
        suggestedClassicTotal = previousTotal;
        foundClassicCrossover = true;
      }
      warmNtt.Observe(2 * limbs, karaMs, nttMs);

      cout << limbs << ',' << limbs * 2 << ','
           << fixed << setprecision(6) << classicMs << ','
           << karaMs << ',' << toom3Ms << ',' << toom5Ms << ',' << nttMs << ',' << parked << ','
           << winner << '\n';
      previousTotal = limbs * 2;
    }

    s.classicMultTotal = suggestedClassicTotal;
    if (warmNtt.first) s.nttMultTotal = warmNtt.first;
    if (s.toom3Total == NTT_MULTIPLICATION_THRESHOLD) s.toom3Total = s.nttMultTotal;
    if (coldNtt.first) s.coldArea = max(coldNtt.first * coldNtt.first, (SizeT)BIGMATH_NTT_AREA_THRESHOLD);

    cout << "suggested CLASSIC_MULTIPLICATION_THRESHOLD ~= "
         << s.classicMultTotal
         << '\n';
    cout << "suggested NTT_MULTIPLICATION_THRESHOLD ~= "
         << s.nttMultTotal
         << '\n';
    cout << "compile override example: -DBIGMATH_CLASSIC_MULTIPLICATION_THRESHOLD="
         << s.classicMultTotal
         << " -DBIGMATH_NTT_MULTIPLICATION_THRESHOLD="
         << s.nttMultTotal
         << '\n';

    PrintHeader("Multiplication Min-Limb Gate");
    cout << "small_limbs,large_limbs,classic_ms,karatsuba_ms,ntt_ms,winner\n";

    vector<SizeT> smallSizes = {4, 8, 16, 24, 32, 40, 48, 64};
    SizeT largeLimbs = full ? 4096 : 1024;

    for (SizeT small : smallSizes)
    {
      vector<DataT> a = RandomNumber(largeLimbs, gen);
      vector<DataT> b = RandomNumber(small, gen);
      int reps = RepsForLimbs(small);

      double classicMs = BestMs([&]() {
        auto r = ClassicMultiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);
      double karaMs = BestMs([&]() {
        auto r = KaratsubaMultiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);
      double nttMs = BestMs([&]() {
        auto r = NTTMultiplication::Multiply(a, b, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);

      string winner = Winner({{"classic", classicMs}, {"karatsuba", karaMs}, {"ntt", nttMs}});
      if (classicWinsPrefix && classicMs * 1.05 < min(karaMs, nttMs))
        suggestedMinLimb = small;
      else
        classicWinsPrefix = false;

      cout << small << ',' << largeLimbs << ','
           << fixed << setprecision(6) << classicMs << ','
           << karaMs << ',' << nttMs << ','
           << winner << '\n';
    }

    if (suggestedMinLimb) s.classicMinLimb = suggestedMinLimb;
    cout << "suggested CLASSIC_MIN_LIMB_THRESHOLD ~= "
         << s.classicMinLimb
         << '\n';
    cout << "compile override example: -DBIGMATH_CLASSIC_MIN_LIMB_THRESHOLD="
         << s.classicMinLimb
         << '\n';
  }

  void TuneSquaring(bool full, ThresholdSuggestions &s)
  {
    PrintHeader("Square Dispatch");
    cout << "limbs,classic_ms,karatsuba_ms,ntt_burst_ms,ntt_parked_ms,winner\n";

    vector<SizeT> sizes = {
        8, 16, 24, 32, 40, 48, 64, 96, 128, 192, 256, 288, 320, 352, 384, 448, 512, 576, 608, 640,
        768, 1024, 1536, 2048, 4096, 8192};
    if (full)
    {
      sizes.push_back(12000);
      sizes.push_back(16000);
      sizes.push_back(24576);
    }

    mt19937_64 gen(0x5A9E5A9E);
    Crossover warmSquare, coldSquare;

    for (SizeT limbs : sizes)
    {
      vector<DataT> a = RandomNumber(limbs, gen);
      int reps = RepsForLimbs(limbs);

      double classicMs = numeric_limits<double>::quiet_NaN();
      if (limbs <= 256)
      {
        classicMs = BestMs([&]() {
          auto r = ClassicSquare::Square(a, BigInteger::Base());
          return (SizeT)r.size();
        }, reps);
      }

      double karaMs = BestMs([&]() {
        auto r = KaratsubaSquare::Square(a, BigInteger::Base());
        return (SizeT)r.size();
      }, reps);

      auto transform = [&]() {
#if BIGMATH_NTT_CRT
        return NttCrt::Multiply(a, a, BigInteger::Base()).size();
#else
        return NTTSquare::Square(a, BigInteger::Base()).size();
#endif
      };
      transform();
      double nttMs = BestMs(transform, reps);
      double parked = ParkedMs(transform);
      string winner = limbs <= 256
                          ? Winner({{"classic", classicMs}, {"karatsuba", karaMs}, {"ntt", nttMs}})
                          : Winner({{"karatsuba", karaMs}, {"ntt", nttMs}});

      warmSquare.Observe(limbs, karaMs, nttMs);
      coldSquare.Observe(limbs, karaMs, parked);

      cout << limbs << ','
           << fixed << setprecision(6) << classicMs << ','
           << karaMs << ',' << nttMs << ',' << parked << ','
           << winner << '\n';
    }

    if (warmSquare.first) s.nttSquare = warmSquare.first;
    if (coldSquare.first) s.coldSquare = max(s.nttSquare, coldSquare.first);
    cout << "suggested NTT_SQUARE_THRESHOLD ~= "
         << s.nttSquare
         << '\n';
    cout << "compile override example: -DBIGMATH_NTT_SQUARE_THRESHOLD="
         << s.nttSquare
         << '\n';
  }

